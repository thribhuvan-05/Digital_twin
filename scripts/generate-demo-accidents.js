const fs = require("node:fs");
const path = require("node:path");

const regions = {
  uk: {
    label: "United Kingdom",
    cities: [
      ["London", -0.1276, 51.5072], ["Manchester", -2.2426, 53.4808],
      ["Birmingham", -1.8904, 52.4862], ["Leeds", -1.5491, 53.8008],
      ["Glasgow", -4.2518, 55.8642], ["Bristol", -2.5879, 51.4545],
      ["Liverpool", -2.9916, 53.4084], ["Sheffield", -1.4701, 53.3811]
    ]
  },
  india: {
    label: "India",
    cities: [
      ["Delhi", 77.1025, 28.7041], ["Mumbai", 72.8777, 19.0760],
      ["Bangalore", 77.5946, 12.9716], ["Chennai", 80.2707, 13.0827],
      ["Kolkata", 88.3639, 22.5726], ["Hyderabad", 78.4867, 17.3850],
      ["Pune", 73.8567, 18.5204], ["Ahmedabad", 72.5714, 23.0225]
    ]
  },
  usa: {
    label: "United States",
    cities: [
      ["New York", -74.0060, 40.7128], ["Los Angeles", -118.2437, 34.0522],
      ["Chicago", -87.6298, 41.8781], ["Houston", -95.3698, 29.7604],
      ["Phoenix", -112.0740, 33.4484], ["Dallas", -96.7970, 32.7767],
      ["Atlanta", -84.3880, 33.7490], ["Seattle", -122.3321, 47.6062]
    ]
  }
};

let seed = 20261119;
function random() {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 4294967296;
}

const records = [];
for (const [country, region] of Object.entries(regions)) {
  region.cities.forEach(([city, longitude, latitude], cityIndex) => {
    for (let index = 0; index < 150; index++) {
      const angle = random() * Math.PI * 2;
      const radius = 0.015 + random() * (country === "india" ? 0.19 : 0.14);
      const longitudeOffset = Math.cos(angle) * radius;
      const latitudeOffset = Math.sin(angle) * radius * 0.72;
      const severityRoll = random();
      records.push({
        Longitude: Number((longitude + longitudeOffset).toFixed(5)),
        Latitude: Number((latitude + latitudeOffset).toFixed(5)),
        country,
        region: city,
        zone: `Z-${String(cityIndex + 1).padStart(2, "0")}`,
        severity: severityRoll < 0.68 ? "low" : severityRoll < 0.92 ? "medium" : "high",
        year: 2022 + (index % 4),
        source: "Roadwise demonstration sample",
        isDemo: true
      });
    }
  });
}

const output = {
  metadata: {
    title: "Roadwise regional demonstration accident data",
    description: "Synthetic, geographically representative sample points for interface, route-risk, and deployment testing. Not for real-world safety decisions.",
    source: "Generated by scripts/generate-demo-accidents.js",
    isDemo: true,
    generatedAt: new Date().toISOString(),
    regions: Object.fromEntries(Object.entries(regions).map(([key, value]) => [key, value.label]))
  },
  accidents: records
};

const outputFile = path.join(__dirname, "..", "clusters.json");
fs.writeFileSync(outputFile, `${JSON.stringify(output, null, 2)}\n`);
console.log(`Generated ${records.length} demo accident records at ${outputFile}`);
